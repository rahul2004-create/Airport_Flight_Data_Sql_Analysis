-- 7. EXAMINE THE RELATIONSHIP BETWEEN CITY POPULATION AND AIRPORT PASSENGER TRAFFIC.

WITH OUTGOING_PASSENGERS AS (
    SELECT ORIGIN_AIRPORT_ID, SUM(PASSENGERS) AS TOT_PASSENGERS
    FROM FLIGHT
    GROUP BY ORIGIN_AIRPORT_ID
),
INCOMING_PASSENGERS AS (
    SELECT DEST_AIRPORT_ID, SUM(PASSENGERS) AS TOT_PASSENGERS
    FROM FLIGHT
    GROUP BY DEST_AIRPORT_ID
),
ALL_AIRPORTS AS (
    SELECT DISTINCT AIRPORT_ID, CITY_NAME FROM AIRPORT
),
PASSENGER_TRAFFIC AS (
    SELECT SUBSTRING_INDEX(AA.CITY_NAME, ',', 1) AS CITY_NAME,
           OP.TOT_PASSENGERS + IP.TOT_PASSENGERS AS TOTAL_PASSENGER_TRAVELLING
    FROM AIRPORT AA
    LEFT JOIN OUTGOING_PASSENGERS OP ON AA.AIRPORT_ID = OP.ORIGIN_AIRPORT_ID
    LEFT JOIN INCOMING_PASSENGERS IP ON AA.AIRPORT_ID = IP.DEST_AIRPORT_ID
    WHERE OP.TOT_PASSENGERS + IP.TOT_PASSENGERS IS NOT NULL
),
CITY_LEVEL_TRAFFIC AS (
    SELECT CITY_NAME, 
    SUM(TOTAL_PASSENGER_TRAVELLING) AS TOTAL_PASSENGER_TRAVELLING
    FROM PASSENGER_TRAFFIC
    GROUP BY CITY_NAME
)

SELECT CP.CITY_NAME, 
		CP.POPULATION, 
		CLT.TOTAL_PASSENGER_TRAVELLING,
        ROUND((CLT.TOTAL_PASSENGER_TRAVELLING/CP.POPULATION),2) AS POP_PASSENGERS_RATIO
FROM CITY_LEVEL_TRAFFIC CLT
JOIN CITY_POP CP ON CLT.CITY_NAME = CP.CITY_NAME
WHERE CP.POPULATION IS NOT NULL AND CLT.TOTAL_PASSENGER_TRAVELLING IS NOT NULL
  AND CP.POPULATION <> 0 
ORDER BY POP_PASSENGERS_RATIO DESC;



-- 8. ASSESS THE IMPACT OF POPULATION SIZE ON FLIGHT FREQUENCY AND ROUTE CHOICES.

WITH ROUTE_FREQ AS
(SELECT  SUBSTRING_INDEX(A1.CITY_NAME,',',1)  AS ORIGIN_CITY,
		 SUBSTRING_INDEX(A2.CITY_NAME,',',1) AS DEST_CITY,
         COUNT(*) AS FLIGHT_FREQUENCY
FROM FLIGHT F 
JOIN AIRPORT A1 ON F.ORIGIN_AIRPORT_ID = A1.AIRPORT_ID
JOIN AIRPORT A2 ON F.DEST_AIRPORT_ID = A2.AIRPORT_ID
GROUP BY 1,2)

SELECT 	RF.ORIGIN_CITY, 
		C1.POPULATION AS ORIGIN_POP,
        RF.DEST_CITY,
        C2.POPULATION AS DEST_POP,
        RF.FLIGHT_FREQUENCY AS TOTAL_FLIGHT_FREQUENSY
FROM ROUTE_FREQ RF
JOIN CITY_POP C1 ON RF.ORIGIN_CITY = C1.CITY_NAME
JOIN CITY_POP C2 ON RF.DEST_CITY = C2.CITY_NAME
GROUP BY 1,2,3,4
ORDER BY 5 DESC;
        

