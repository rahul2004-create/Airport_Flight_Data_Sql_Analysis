-- 1. Analyze total passenger traffic per route and over time.

-- TOP 10 BUSIEST PASSENGER TRAFFIC ROUTE

SELECT  
		A1.CITY_NAME AS ORIGIN_CITY,
		A2.CITY_NAME AS DEST_CITY,
       SUM(F.PASSENGERS) AS TOTAL_PASSENGERS,
       F.YEAR,
       F.QUARTER
FROM FLIGHT F
LEFT JOIN AIRPORT A1 ON F.ORIGIN_AIRPORT_ID = A1.AIRPORT_ID
LEFT JOIN AIRPORT A2 ON F.DEST_AIRPORT_ID = A2.AIRPORT_ID
GROUP BY 1,2,4,5
ORDER BY  TOTAL_PASSENGERS DESC
LIMIT 10;




-- Least busiest routes


SELECT A1.CITY_NAME AS ORIGIN_CITY, A2.CITY_NAME AS DEST_CITY,
       SUM(F.PASSENGERS) AS TOTAL_PASSENGERS
FROM FLIGHT F
JOIN AIRPORT A1 ON F.ORIGIN_AIRPORT_ID = A1.AIRPORT_ID
JOIN AIRPORT A2 ON F.DEST_AIRPORT_ID = A2.AIRPORT_ID
WHERE A1.CITY_NAME <> A2.CITY_NAME 
GROUP BY A1.CITY_NAME, A2.CITY_NAME
HAVING SUM(F.PASSENGERS) > 0
ORDER BY TOTAL_PASSENGERS ASC
LIMIT 5;





-- 2. Determine average passengers per flight for various routes and airportS


-- FOR ROUTES

SELECT A1.CITY_NAME AS ORIGIN_CITY, A2.CITY_NAME AS DEST_CITY, 
       round(AVG(F.PASSENGERS)) AS AVG_PASSENGERS
FROM FLIGHT F
JOIN AIRPORT A1 ON F.ORIGIN_AIRPORT_ID = A1.AIRPORT_ID
JOIN AIRPORT A2 ON F.DEST_AIRPORT_ID = A2.AIRPORT_ID
GROUP BY 1,2
ORDER BY AVG_PASSENGERS DESC;




-- FOR AIRPORTS

WITH OUTGOING_PASSENGERS AS (
    SELECT ORIGIN_AIRPORT_ID, AVG(PASSENGERS) AS AVG_PASSENGERS
    FROM FLIGHT
    GROUP BY ORIGIN_AIRPORT_ID),
    
INCOMING_PASSENGERS AS (
    SELECT DEST_AIRPORT_ID, AVG(PASSENGERS) AS AVG_PASSENGERS
    FROM FLIGHT
    GROUP BY DEST_AIRPORT_ID),
    
ALL_AIRPORTS AS (
    SELECT DISTINCT ORIGIN_AIRPORT_ID AS AIRPORT_ID FROM FLIGHT
    UNION
    SELECT DISTINCT DEST_AIRPORT_ID AS AIRPORT_ID FROM FLIGHT
)
SELECT AA.AIRPORT_ID, A.CITY_NAME,
       round(OP.AVG_PASSENGERS + IP.AVG_PASSENGERS) AS TOTAL_AVG_PASSENGER
FROM ALL_AIRPORTS AA
LEFT JOIN AIRPORT A ON AA.AIRPORT_ID = A.AIRPORT_ID
LEFT JOIN OUTGOING_PASSENGERS OP ON AA.AIRPORT_ID = OP.ORIGIN_AIRPORT_ID
LEFT JOIN INCOMING_PASSENGERS IP ON AA.AIRPORT_ID = IP.DEST_AIRPORT_ID
WHERE    round(OP.AVG_PASSENGERS + IP.AVG_PASSENGERS)  IS NOT NULL
ORDER BY 3 DESC;




-- 3. Assess flight frequency and identify high-traffic corridors.


SELECT A1.CITY_NAME AS ORIGIN_CITY, A2.CITY_NAME AS DEST_CITY,
       COUNT(*) AS FLIGHT_FREQUENCY
FROM FLIGHT F
JOIN AIRPORT A1 ON F.ORIGIN_AIRPORT_ID = A1.AIRPORT_ID
JOIN AIRPORT A2 ON F.DEST_AIRPORT_ID = A2.AIRPORT_ID
GROUP BY 1,2
ORDER BY FLIGHT_FREQUENCY DESC
LIMIT 5;







-- 4. Compare passenger numbers across origin cities to identify top-performing airports.

SELECT A.CITY_NAME AS ORIGIN_CITY, 
		SUM(F.PASSENGERS) AS TOTAL_PASSENGERS,
		COUNT(F.AIRLINE_ID) AS FREQUENSY
FROM FLIGHT F JOIN AIRPORT A ON
F.ORIGIN_AIRPORT_ID = A.AIRPORT_ID
GROUP BY 1
ORDER BY 3 DESC  
LIMIT 10;






-- 5. Evaluate available seat capacity to understand seat utilization.


WITH SEATING_CAPACITY AS
(select AIRLINE_ID, max(PASSENGERS) as seat_capacity
from FLIGHT
group by 1
having max(PASSENGERS) > 0),

SEAT_UTI AS 
(SELECT SC.AIRLINE_ID, (F.PASSENGERS*100)/SC.SEAT_CAPACITY AS SEAT_UTILIZING
FROM SEATING_CAPACITY AS SC  JOIN FLIGHT F ON
SC.AIRLINE_ID = F.AIRLINE_ID)

SELECT SC.AIRLINE_ID , AI.CARRIER_NAME,
		ROUND(AVG(SC.SEAT_UTILIZING),2) AS AVG_S_UTILIZING
FROM SEAT_UTI  SC JOIN AIRLINE AI ON
SC.AIRLINE_ID = AI.AIRLINE_ID
GROUP BY 1,2
ORDER BY AVG_S_UTILIZING DESC
LIMIT 10;


-- OBJECTIVE 6: IDENTIFY POPULAR DESTINATION AIRPORTS BASED ON INBOUND PASSENGER COUNTS.



SELECT F.DEST_AIRPORT_ID ,A.CITY_NAME AS DEST_CITY , A.AIRPORT_CODE AS DEST_CODE, SUM(F.PASSENGERS) AS TOTAL_PASSENGERS
